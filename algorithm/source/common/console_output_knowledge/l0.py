def _output(
    path: str,
    label: str,
    description: str,
    effect: str,
    business_meaning: str,
    interpretation: str,
    quality_check: str,
    abnormal_signs: list[str],
    downstream_use: str,
    misuse_warning: str,
    **kwargs: Any,
) -> dict[str, Any]:
    """以紧凑形式声明一条完整的专业输出知识。"""
    return make_output(
        path,
        label,
        description=description,
        effect=effect,
        business_meaning=business_meaning,
        interpretation=interpretation,
        quality_check=quality_check,
        abnormal_signs=abnormal_signs,
        downstream_use=downstream_use,
        misuse_warning=misuse_warning,
        **kwargs,
    )


def _summary(what: str, value: str, caution: str) -> dict[str, str]:
    """构造算法级摘要。"""
    return {"what": what, "value": value, "caution": caution}


