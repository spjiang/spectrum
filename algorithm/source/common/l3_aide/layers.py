def list_layers() -> list[dict[str, Any]]:
    """侧栏用的层目录。"""
    return [
        {
            "id": row["id"],
            "level": row["level"],
            "title": row["title"],
            "kicker": row["kicker"],
            "benefit": row["benefit"],
        }
        for row in LAYERS.values()
    ]


def get_layer(layer_id: str) -> dict[str, Any] | None:
    """返回案例副本；有分步故事时补一份给模型用的纯文本。"""
    row = LAYERS.get(layer_id)
    if row is None:
        return None
    out = dict(row)
    story = out.get("story") or []
    if story and not out.get("context"):
        out["context"] = [str(item.get("text") or "") for item in story if isinstance(item, dict)]
    return out
